// 自动保存的节奏（00 号计划书 §7.2、§7.3，M3-P4 设计 §3.1–§3.3、§3.8）：两级——捕获进内存里的"最近一次捕获"，上传取它上传。
// 页面按这些数调度，E2E 与页面自检引用同一组数（与 EDIT_LEASE_* 同样的做法）。都是起始参数，经 M7 的实测再调整（计划书 §7.2）。

/** 捕获的静默（毫秒）：修改（与组合输入的结束）停下这么久、公式收齐、不在组字，才捕获（计划书 §7.3） */
export const AUTOSAVE_CAPTURE_QUIET_MS = 1000

/**
 * 捕获的上限（毫秒）：从最近一次捕获之后的第一处修改算起，最长这么久必定捕获一次——同时约束公式收齐与组合输入的等待；
 * 到了上限公式还没收齐就照常捕获、带上"公式待更新"，收齐之后补捕获（计划书 §7.3）。显式保存等公式也以它为上限（从按下算，P4 设计 §3.4）
 */
export const AUTOSAVE_CAPTURE_MAX_MS = 3000

/** 上传的静默（毫秒）：修改停下这么久、而且捕获已经覆盖了全部修改，就上传最近一次捕获（计划书 §7.2） */
export const AUTOSAVE_UPLOAD_QUIET_MS = 2000

/** 上传的上限（毫秒）：持续编辑时，从第一处还没上传的修改算起最长这么久上传一次（上传的是最近一次捕获，计划书 §7.2） */
export const AUTOSAVE_UPLOAD_MAX_MS = 15_000

/** 自动重试的退避起点（毫秒）：之后每次失败翻倍（P4 设计 §3.8） */
export const AUTOSAVE_RETRY_INITIAL_MS = 2000

/** 自动重试的退避上限（毫秒）：503 带的 Retry-After 更长时按它，至多 AUTOSAVE_RETRY_AFTER_MAX_MS（P4 设计 §3.8） */
export const AUTOSAVE_RETRY_MAX_MS = 60_000

/**
 * 服务端给的 Retry-After 至多按多久算（毫秒，P4 设计 §3.8，复验 C2）：本服务给的是几秒；更长的（反向代理的维护页、写错的值）
 * 按它，到点照常再试——自动保存不因一个异常的值停上几小时、几天，浏览器的计时器也不会溢出（超过 2^31−1 毫秒立即触发，页面空转）
 */
export const AUTOSAVE_RETRY_AFTER_MAX_MS = 300_000

/**
 * 大文档拉长捕获的间隔（计划书 §7.2 的"大文档"一行）：上一次捕获结束之后，至少隔开它的耗时的这么多倍才再捕获，
 * 同步捕获占主线程的比例不超过约十分之一（5 MiB 的捕获约 80 ms，隔开约 0.8 秒，平常的文档不受影响）
 */
export const AUTOSAVE_CAPTURE_SPACING_FACTOR = 10
