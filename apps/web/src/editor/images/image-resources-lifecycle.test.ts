import type { AssetBytes } from '../../shared/assets/asset-api.ts'
import type { DecodedImage } from './decode-image.ts'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { deferred } from '../async-tools.ts'
import { BYTES, decoded, OTHER, PLACEHOLDER, resourcesHarness, SOURCE } from './image-resources.test-support.ts'

afterEach(() => {
  vi.restoreAllMocks()
  vi.useRealTimers()
})

describe('图片资源的代次与退役', () => {
  it('未交给 SDK 的内部解码元素在刷新后释放，不继续跟随新一轮像素', async () => {
    const h = resourcesHarness()
    const first = decoded('blob:https://app.test/internal-first')
    const second = decoded('blob:https://app.test/internal-second')
    h.decode.mockResolvedValueOnce(first).mockResolvedValueOnce(second)
    await h.resources.load(SOURCE)
    // 没有 cached/track，调用方只拿到了 URL，旧解码元素不再由任何 SDK 图元使用。
    h.resources.refresh()
    await h.resources.load(SOURCE)
    expect(first.image.hasAttribute('src')).toBe(false)
    expect(first.dispose).toHaveBeenCalledTimes(1)
    h.resources.dispose()
    expect(second.image.hasAttribute('src')).toBe(false)
  })

  it.each(['suspend', 'dispose'] as const)('%s 及时取消忽略 signal 的读取，晚结果不解码、不显示', async (stop) => {
    const pending = deferred<AssetBytes>()
    const h = resourcesHarness()
    h.read.mockReturnValue(pending.promise)
    const task = h.resources.load(SOURCE).catch((error: unknown) => error)
    await vi.waitFor(() => expect(h.read).toHaveBeenCalledTimes(1))
    const signal = h.read.mock.calls[0]?.[1]
    h.resources[stop]()
    expect(await task).toMatchObject({ name: 'AbortError' })
    expect(signal?.aborted).toBe(true)
    pending.resolve(BYTES)
    await Promise.resolve()
    await Promise.resolve()
    expect(h.decode).not.toHaveBeenCalled()
    expect(h.resources.cached(SOURCE)).toBeUndefined()
    expect(h.failed).not.toHaveBeenCalled()
    h.resources.dispose()
  })

  it('旧解码忽略取消：旧调用及时拒绝，晚到对象 URL 仍释放', async () => {
    const pending = deferred<DecodedImage>()
    const h = resourcesHarness()
    h.decode.mockReturnValueOnce(pending.promise)
    const task = h.resources.load(SOURCE).catch((error: unknown) => error)
    await vi.waitFor(() => expect(h.decode).toHaveBeenCalledTimes(1))
    h.resources.refresh()
    expect(await task).toMatchObject({ name: 'AbortError' })
    expect(await h.resources.load(SOURCE)).toBe('blob:https://app.test/first')
    const late = decoded('blob:https://app.test/late')
    pending.resolve(late)
    await vi.waitFor(() => expect(late.dispose).toHaveBeenCalledTimes(1))
    expect(h.resources.cached(SOURCE)?.src).toBe('blob:https://app.test/first')
    expect(h.failed).not.toHaveBeenCalled()
    h.resources.dispose()
  })

  it('刷新当场清掉 SDK 与共用缓存元素，慢重读期间不能显示旧图', async () => {
    const h = resourcesHarness()
    const original = decoded()
    h.decode.mockResolvedValueOnce(original)
    await h.resources.load(SOURCE)
    const a = document.createElement('img')
    const b = document.createElement('img')
    h.resources.track(SOURCE, a)
    h.resources.track(SOURCE, b)
    const pending = deferred<AssetBytes>()
    h.read.mockReturnValueOnce(pending.promise)
    h.resources.refresh()
    expect(a.src).toBe(PLACEHOLDER)
    expect(b.src).toBe(PLACEHOLDER)
    expect(original.image.src).not.toBe(original.url)
    expect(original.dispose).toHaveBeenCalledTimes(1)
    expect(h.resources.cached(SOURCE)).toBeUndefined()
    h.resources.suspend()
    pending.resolve(BYTES)
    h.resources.dispose()
  })

  it('连续刷新只接纳最后一轮，前两轮旧图不能覆盖新图', async () => {
    const h = resourcesHarness()
    const first = deferred<AssetBytes>()
    const second = deferred<AssetBytes>()
    h.read.mockReturnValueOnce(first.promise).mockReturnValueOnce(second.promise)
    const task = h.resources.load(SOURCE).catch((error: unknown) => error)
    await vi.waitFor(() => expect(h.read).toHaveBeenCalledTimes(1))
    h.resources.refresh()
    await vi.waitFor(() => expect(h.read).toHaveBeenCalledTimes(2))
    h.resources.refresh()
    expect(await task).toMatchObject({ name: 'AbortError' })
    expect(await h.resources.load(SOURCE)).toBe('blob:https://app.test/first')
    first.resolve(BYTES)
    second.resolve(BYTES)
    await Promise.resolve()
    await Promise.resolve()
    expect(h.decode).toHaveBeenCalledTimes(1)
    expect(h.failed).not.toHaveBeenCalled()
    h.resources.dispose()
  })

  it('暂停时 load/download 不发请求，恢复从新一代开始', async () => {
    const h = resourcesHarness()
    await h.resources.load(SOURCE)
    h.resources.suspend()
    await expect(h.resources.load(SOURCE)).rejects.toMatchObject({ name: 'AbortError' })
    await expect(h.resources.download(SOURCE)).rejects.toMatchObject({ name: 'AbortError' })
    expect(h.read).toHaveBeenCalledTimes(1)
    h.resources.refresh()
    await h.resources.load(SOURCE)
    expect(h.read).toHaveBeenCalledTimes(2)
    h.resources.dispose()
  })

  it('永久退役不能被 refresh 复活；迟到 track 立即清空，不产生新请求', async () => {
    const h = resourcesHarness()
    const original = decoded()
    h.decode.mockResolvedValueOnce(original)
    await h.resources.load(SOURCE)
    h.resources.dispose()
    h.resources.dispose()
    h.resources.refresh()
    await expect(h.resources.load(SOURCE)).rejects.toMatchObject({ name: 'AbortError' })
    const late = document.createElement('img')
    late.src = original.url
    h.resources.track(SOURCE, late)
    expect(late.src).toBe(PLACEHOLDER)
    expect(original.dispose).toHaveBeenCalledTimes(1)
    expect(h.read).toHaveBeenCalledTimes(1)
  })

  it('下载与显示在途交错时都在同一代取消，不把下载对象留进显示缓存', async () => {
    const h = resourcesHarness()
    const display = deferred<DecodedImage>()
    const download = deferred<DecodedImage>()
    h.decode.mockReturnValueOnce(display.promise).mockReturnValueOnce(download.promise)
    const drawingTask = h.resources.load(SOURCE).catch((error: unknown) => error)
    await vi.waitFor(() => expect(h.decode).toHaveBeenCalledTimes(1))
    const downloadTask = h.resources.download(SOURCE).catch((error: unknown) => error)
    await vi.waitFor(() => expect(h.decode).toHaveBeenCalledTimes(2))
    h.resources.suspend()
    expect(await drawingTask).toMatchObject({ name: 'AbortError' })
    expect(await downloadTask).toMatchObject({ name: 'AbortError' })
    const a = decoded('blob:https://app.test/late-display')
    const b = decoded('blob:https://app.test/late-download')
    display.resolve(a)
    download.resolve(b)
    await vi.waitFor(() => {
      expect(a.dispose).toHaveBeenCalledTimes(1)
      expect(b.dispose).toHaveBeenCalledTimes(1)
    })
    expect(h.resources.cached(SOURCE)).toBeUndefined()
    h.resources.dispose()
  })

  it('刷新失败留下占位，下一次显式刷新才重试', async () => {
    const h = resourcesHarness()
    await h.resources.load(SOURCE)
    const image = document.createElement('img')
    h.resources.track(SOURCE, image)
    h.read.mockRejectedValueOnce(new Error('offline'))
    h.resources.refresh()
    expect(await h.resources.load(SOURCE)).toBe(PLACEHOLDER)
    expect(image.src).toBe(PLACEHOLDER)
    expect(h.read).toHaveBeenCalledTimes(2)
    h.resources.refresh()
    await h.resources.load(SOURCE)
    expect(image.src).toBe('blob:https://app.test/first')
    expect(h.read).toHaveBeenCalledTimes(3)
    h.resources.dispose()
  })

  it('一张图改源不影响同源的另一张，旧源重读只更新仍属旧源的元素', async () => {
    const h = resourcesHarness()
    await h.resources.load(SOURCE)
    const a = document.createElement('img')
    const b = document.createElement('img')
    h.resources.track(SOURCE, a)
    h.resources.track(SOURCE, b)
    h.decode.mockResolvedValueOnce(decoded('blob:https://app.test/other'))
    await h.resources.load(OTHER)
    h.resources.track(OTHER, a)
    expect(b.src).toBe('blob:https://app.test/first')
    expect(a.src).toBe('blob:https://app.test/other')
    h.decode.mockResolvedValueOnce(decoded('blob:https://app.test/refreshed-source')).mockResolvedValueOnce(decoded('blob:https://app.test/refreshed-other'))
    h.resources.refresh()
    await Promise.all([h.resources.load(SOURCE), h.resources.load(OTHER)])
    expect(a.src).toBe('blob:https://app.test/refreshed-other')
    expect(b.src).toBe('blob:https://app.test/refreshed-source')
    h.resources.dispose()
  })

  it('读取/解码完成后移除取消监听，不给下一轮遗留监听', async () => {
    const add = vi.spyOn(AbortSignal.prototype, 'addEventListener')
    const remove = vi.spyOn(AbortSignal.prototype, 'removeEventListener')
    const h = resourcesHarness()
    await h.resources.load(SOURCE)
    const added = add.mock.calls.filter(([event]) => event === 'abort').map(([, listener]) => listener)
    expect(added.length).toBeGreaterThan(0)
    for (const listener of added)
      expect(remove.mock.calls.some(([event, removed]) => event === 'abort' && removed === listener)).toBe(true)
    h.resources.dispose()
  })
})
